export const save = (function(){
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (raw) {
      const s = JSON.parse(raw);
      return {
        unlocked: Math.max(INITIAL_UNLOCKED, Math.min(LEVELS.length, s.unlocked || INITIAL_UNLOCKED)),
        stars: s.stars || {},
        best: s.best || {}
      };
    }
  } catch(e){}
  return { unlocked: INITIAL_UNLOCKED, stars: {}, best: {} };
})();

export function persist() {
  try { localStorage.setItem(SAVE_KEY, JSON.stringify(save)); }
  catch(e){}
  if (navigator.storage && navigator.storage.persist) navigator.storage.persist().catch(()=>{});
}

export function totalStars() {
  let t = 0;
  for (const k in save.stars) t += save.stars[k] || 0;
  return t;
}

export function totalScore() {
  let t = 0;
  for (const k in save.best) t += save.best[k] || 0;
  return t;
}
